class MultiCriterionClassifier(ArticleClassifier):
    """
    Combine the opinions of an arbitrary set of classifiers to arrive at a more informed conclusion.
    """
    def __init__(self, classifiers_with_bools, threshold=None):
        """
        Initialize the classifier.

        Inputs:
            classifers_with_bools: list of (classifier, score_if_relevant) tuples of a RelevanceClassifier object and a boolean value.
            score_if_relevant should be one of {True, False} and should be the score that turns up when an item is relevant.
            threshold: must satisfy strictly more than this number of classifiers in order to be marked relevant.
        """
        self.values_if_relevant = []
        self.classifiers = []
        
        # if no threshold is expressed, everyone has to agree
        if threshold is None:
            self.threshold = len(classifiers_with_bools) - 1
        else:
            # you can also set your own threshold
            self.threshold = threshold

        for clf, val_if_relevant in classifiers_with_bools:
            self.values_if_relevant.append(val_if_relevant)
            self.classifiers.append(clf)

    def predict(self, X_data):
        """
        Given a tuple of inputs as (input_for_clf_1, input_for_clf_2, ...input_for_clf_k),
        run each classifier against its input and then check whether enough classifiers are satisfied with the input's relevance.
        Return pred, a vector of bools.
        """
        pred_bools = np.array([c.predict(x) for c, x in zip(self.classifiers, X_data)])
        pred_scores = [np.sum(row == self.values_if_relevant) for row in pred_bools.T]
        pred = [p > self.threshold for p in pred_scores]
        return pred 

class MultiFrameClassifier(ArticleClassifier):
    def __init__(self, frames, run_save_dir=None, clf_type='NB', device='cuda'):
        self.frames = frames
        self.clf_type = clf_type
        if self.clf_type == "NB":
            self.frame_classifiers = {frame: NBClassifier(input_type='text') for frame in self.frames}
        elif self.clf_type == "BERT":
            if run_save_dir is None:
                raise ValueError("need a run save dir")
            else:
                self.frame_classifiers = {frame: BERTClassifier(frame, run_save_dir, device) for frame in self.frames}
        elif self.clf_type == 'DeBERTa':
            if run_save_dir is None:
                raise ValueError("need a save dir")
            else:
                self.frame_classifiers = {frame: DeBERTaClassifier(frame, run_save_dir, device) for frame in self.frames}
            
    def fit(self, X_train, ys_train, X_val=None, ys_val=None):
        for frame in self.frames:
            if self.clf_type == 'NB':
                self.frame_classifiers[frame].fit(X_train, ys_train[frame])
            elif self.clf_type == "BERT":
                df_train = pd.concat((X_train, ys_train), axis=1)
                df_val = pd.concat((X_val, ys_val), axis=1)
                self.frame_classifiers[frame].train_with_validation(df_train, df_val)
            elif self.clf_type == "DeBERTa":
                df_train = pd.concat((X_train, ys_train), axis=1)
                df_val = pd.concat((X_val, ys_val), axis=1)
                self.frame_classifiers[frame].train_with_validation(df_train, df_val)
                
    def predict(self, X_pred):
        return {frame: self.frame_classifiers[frame].predict(X_pred) for frame in self.frames}

    def frac_predict(self, X_pred):
        return {frame: self.frame_classifiers[frame].frac_predict(X_pred) for frame in self.frames}
        
    def accuracy_pr_kappa(self, X_test, ys_test):
        preds = self.predict(X_test)
        metrics = {}
        for frame in self.frames:
            guess = preds[frame]
            y_test = ys_test[frame]
            accuracy = accuracy_score(y_test, guess)
            precision = precision_score(y_test, guess)
            recall = recall_score(y_test, guess)
            my_f1_score = f1_score(y_test, guess)
            kappa = cohen_kappa_score(y_test, guess)

            metrics[frame] = {
                'accuracy': accuracy,
                'precision': precision,
                'recall': recall,
                'f1': my_f1_score,
                'kappa': kappa,
            }
        return metrics
     
