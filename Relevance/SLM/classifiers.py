class ArticleClassifier(object):
    """
    Base class for relevance classification of text data. 
    Probably don't try to use the base class for anything.
    """
    def __init__(self):
        """
        Sets up a classifier and a (optionally tuneable) threshold for classification
        """
        self.classifier = None # some function that classifies text
        self.threshold = 0.0 # in case we need to tune bias or whatever

    def fit(self, X_train, y_train):
        """
        Will be unique to every child class
        """
        pass

    def accuracy_pr_kappa(self, X_test, y_test):
        """
        Runs the classifier on X_test, which should be an array of texts.
        Compares the classifications it gets to y_test, which is the list of ground truth categorizations for X_test.

        Returns a dict of metrics:
            accuracy
            precision
            recall
            F1 score
            Cohen's Kappa
        """
        guess = self.predict(X_test) # prediction step
        accuracy = accuracy_score(y_test, guess)
        precision = precision_score(y_test, guess)
        recall = recall_score(y_test, guess)
        my_f1_score = f1_score(y_test, guess)
        kappa = cohen_kappa_score(y_test, guess)
        # return a dict of metrics wow
        return {'accuracy': accuracy, 
                'precision': precision, 
                'recall': recall, 
                'f1': my_f1_score, 
                'cohen_kappa': kappa
                }

    def predict(self, X_data):
        """
        Returns a list of classifier predictions; assumes self.classifier is a function/callable that takes in a string.
        """
        return [self.classifier(x) for x in X_data]


class WordRelevanceClassifier(ArticleClassifier):
    """
    Given a list of words and a threshold number of times they should appear in order for the article/keyword list to be considered relevant,
    tag an article or keyword list for relevance.
    """
    def __init__(self, threshold=0, source='keywords', keywords=set(['mpox', 'monkeypox'])):
        """
        Instantiate the class.

        Params:
            threshold: the min number of words that should appear in order for the article/keyword list to be counted as relevant. 
                for keywords, we see each keyword listed once per article. for article text, a word may be repeated and therefore count twice.
            source: one of {keywords, text}. keywords = the keyword list generated by newspaper4k; text = the raw article text
            keywords: a set of lowercase strings corresponding to some keywords that ought to be predictive of relevance.
        """
        self.mpox_keywords = keywords
        self.threshold = threshold
        if source == 'keywords':
            # make an anonymous function that splits up the keyword list (which is a literal of a list) and checks how many of them are in our keyword list
            self.classifier = lambda b: len(set([w.strip() for w in b.lower()[2:-2].split("', '")]).intersection(self.mpox_keywords)) > self.threshold
        elif source == 'text':
            # checks how many times our keywords show up in our article text and compares it to self.threshold.
            self.classifier = lambda b: self.get_counts_from_text(b) > self.threshold
        else:
            raise ValueError("good luck trying to analyze that column buddy")

    def get_counts_from_text(self, text):
        """
        Get the number of times our keywords show up in the text (X instances of word Y = X points)

        text: a string (article text)

        returns: the total number of keyword hits as explained above.
        """
        ct = collections.Counter([w.strip() for w in text.lower().split() if w not in ENG_STOPWORDS])
        tot_hits = sum([ct[k] for k in self.mpox_keywords])
        return tot_hits

    def fit(self, X_train, y_train):
        """
        We aren't actually fitting anything here lol
        """
        raise NotImplementedError("This function is too dumb to have a train function!")

class NBClassifier(ArticleClassifier):
    """
    Naive Bayes classifier for article relevance; can look at keywords or article text.
    """
    def __init__(self, input_type='keywords'):
        """
        Instantiates the object

        Params:
        input_type: lets us know if we're looking at keywords or article text ({'keywords', 'text'} and all others are invalid)
        """
        self.classifier = MultinomialNB() # multinomial Naive Bayes
        self.vectorizer = CountVectorizer(
            strip_accents = 'ascii', 
            lowercase = True,
            stop_words='english', # performs marginally better when stopwords are removed
        )
        if input_type == 'keywords':
            # same text parsing of literal list as before
            self.input_parser = lambda b: b.lower()[2:-2].replace(',', ' ')
        elif input_type == 'text':
            # grab all words that aren't stopwords
            self.input_parser = lambda b: ' '.join([s for s in b.lower().split() if s not in ENG_STOPWORDS])
        else:
            raise ValueError("good luck trying to analyze that column buddy")

    def fit(self, X_train, y_train):
        """
        Given X_train (list of strings, either keywords or article text), and y_train (binary vector),
        train a Naive Bayes classifier to label the strings for relevance.
        """
        # train the vectorizer on training data
        self.vectorizer_fit = self.vectorizer.fit(X_train)
        # vectorize the training data
        x_train_transformed = self.vectorizer_fit.transform(X_train)
        # fit the classifier to the training data
        self.classifier = self.classifier.fit(x_train_transformed, y_train)

    def predict(self, X_data):
        """
        Runs the X_data (list of strings) through the vectorizer and then classifies the resulting count vectors.
        """
        x_transformed = self.vectorizer_fit.transform(X_data)

        return self.classifier.predict(x_transformed)

    def frac_predict(self, X_data):
        """
        Runs the X_data (list of strings) through the vectorizer and then produces a probability for the resulting count vectors.
        """
        x_transformed = self.vectorizer_fit.transform(X_data)

        return self.classifier.predict_proba(x_transformed)

